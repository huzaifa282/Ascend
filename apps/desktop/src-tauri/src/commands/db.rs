//! Single mutex-guarded SQLite connection, exposed to the frontend as three
//! commands that `packages/db`'s Drizzle `sqlite-proxy` driver calls into.
//!
//! See docs/decisions.md ("Custom rusqlite command layer instead of
//! tauri-plugin-sql") for why this exists instead of the pooled plugin: a
//! pool can silently split a `BEGIN`/`COMMIT` pair across two physical
//! connections, breaking atomicity. One connection makes that impossible by
//! construction. `db_batch_atomic` is the only place a real transaction is
//! opened; `db_select`/`db_execute` are always single statements.

use include_dir::{include_dir, Dir};
use rusqlite::{params_from_iter, types::Value as SqlValue, Connection};
use serde::{Deserialize, Serialize};
use serde_json::Value as JsonValue;
use std::sync::Mutex;
use std::time::{SystemTime, UNIX_EPOCH};
use tauri::{AppHandle, Manager, State};

/// Generated by `pnpm --filter @ascendant/db db:generate` (drizzle-kit).
static MIGRATIONS: Dir = include_dir!("$CARGO_MANIFEST_DIR/../../../packages/db/migrations");

pub struct AppDb(pub Mutex<Connection>);

#[derive(Serialize)]
pub struct SelectResult {
    pub rows: Vec<Vec<JsonValue>>,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ExecuteResult {
    pub rows_affected: i64,
    pub last_insert_rowid: i64,
}

#[derive(Deserialize)]
pub struct BatchStatement {
    pub sql: String,
    pub params: Vec<JsonValue>,
}

fn json_to_sql(v: &JsonValue) -> SqlValue {
    match v {
        JsonValue::Null => SqlValue::Null,
        // SQLite has no native boolean; drizzle's `{mode:'boolean'}` columns
        // bind 0/1 (spec 12.1-adjacent: never store booleans any other way).
        JsonValue::Bool(b) => SqlValue::Integer(if *b { 1 } else { 0 }),
        JsonValue::Number(n) => n
            .as_i64()
            .map(SqlValue::Integer)
            .unwrap_or_else(|| SqlValue::Real(n.as_f64().unwrap_or(0.0))),
        JsonValue::String(s) => SqlValue::Text(s.clone()),
        // JSON-mode columns are pre-stringified by drizzle before the param
        // ever reaches here; arrays/objects only land here on a bug upstream.
        other => SqlValue::Text(other.to_string()),
    }
}

fn sql_value_to_json(v: rusqlite::types::ValueRef) -> JsonValue {
    use rusqlite::types::ValueRef;
    match v {
        ValueRef::Null => JsonValue::Null,
        ValueRef::Integer(i) => JsonValue::from(i),
        ValueRef::Real(f) => JsonValue::from(f),
        ValueRef::Text(t) => JsonValue::String(String::from_utf8_lossy(t).into_owned()),
        ValueRef::Blob(b) => JsonValue::String(String::from_utf8_lossy(b).into_owned()),
    }
}

fn to_params(values: &[JsonValue]) -> Vec<SqlValue> {
    values.iter().map(json_to_sql).collect()
}

#[tauri::command]
pub fn db_select(
    db: State<AppDb>,
    sql: String,
    params: Vec<JsonValue>,
) -> Result<SelectResult, String> {
    let conn = db.0.lock().map_err(|e| e.to_string())?;
    let mut stmt = conn.prepare(&sql).map_err(|e| e.to_string())?;
    let col_count = stmt.column_count();
    let mut rows = stmt
        .query(params_from_iter(to_params(&params)))
        .map_err(|e| e.to_string())?;

    let mut out = Vec::new();
    while let Some(row) = rows.next().map_err(|e| e.to_string())? {
        let mut values = Vec::with_capacity(col_count);
        for i in 0..col_count {
            values.push(sql_value_to_json(row.get_ref(i).map_err(|e| e.to_string())?));
        }
        out.push(values);
    }
    Ok(SelectResult { rows: out })
}

#[tauri::command]
pub fn db_execute(
    db: State<AppDb>,
    sql: String,
    params: Vec<JsonValue>,
) -> Result<ExecuteResult, String> {
    let conn = db.0.lock().map_err(|e| e.to_string())?;
    let rows_affected = conn
        .execute(&sql, params_from_iter(to_params(&params)))
        .map_err(|e| e.to_string())?;
    Ok(ExecuteResult {
        rows_affected: rows_affected as i64,
        last_insert_rowid: conn.last_insert_rowid(),
    })
}

/// The only place a real transaction is opened — see the module doc comment.
#[tauri::command]
pub fn db_batch_atomic(db: State<AppDb>, statements: Vec<BatchStatement>) -> Result<(), String> {
    let conn = db.0.lock().map_err(|e| e.to_string())?;
    conn.execute_batch("BEGIN IMMEDIATE").map_err(|e| e.to_string())?;
    for statement in &statements {
        if let Err(err) = conn.execute(&statement.sql, params_from_iter(to_params(&statement.params))) {
            let _ = conn.execute_batch("ROLLBACK");
            return Err(err.to_string());
        }
    }
    conn.execute_batch("COMMIT").map_err(|e| e.to_string())?;
    Ok(())
}

fn now_ms() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

fn run_migrations(conn: &Connection) -> rusqlite::Result<()> {
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS _migrations (name TEXT PRIMARY KEY, applied_at INTEGER NOT NULL)",
    )?;

    let mut files: Vec<_> = MIGRATIONS
        .files()
        .filter(|f| f.path().extension().is_some_and(|e| e == "sql"))
        .collect();
    files.sort_by_key(|f| f.path().to_path_buf());

    for file in files {
        let name = file.path().file_name().unwrap().to_string_lossy().to_string();
        let already_applied: i64 = conn.query_row(
            "SELECT COUNT(*) FROM _migrations WHERE name = ?1",
            [&name],
            |r| r.get(0),
        )?;
        if already_applied > 0 {
            continue;
        }
        let sql = file.contents_utf8().unwrap_or_default();
        conn.execute_batch(sql)?;
        conn.execute(
            "INSERT INTO _migrations (name, applied_at) VALUES (?1, ?2)",
            rusqlite::params![name, now_ms()],
        )?;
    }
    Ok(())
}

/// Opens the single app connection (in the OS app-data directory), applies
/// any pending migrations, and returns it ready to be `app.manage()`d.
pub fn init_db(app_handle: &AppHandle) -> rusqlite::Result<Connection> {
    let app_dir = app_handle
        .path()
        .app_data_dir()
        .expect("resolve app data dir");
    std::fs::create_dir_all(&app_dir).expect("create app data dir");
    let db_path = app_dir.join("ascendant.sqlite");

    let conn = Connection::open(db_path)?;
    // A second launched instance (before the single-instance plugin's callback
    // runs, or on platforms where it's a no-op) would otherwise hit
    // SQLITE_BUSY immediately and abort via the `expect` below — wait up to
    // 5s for the first instance's write to finish instead.
    conn.execute_batch("PRAGMA foreign_keys = ON; PRAGMA journal_mode = WAL; PRAGMA busy_timeout = 5000;")?;
    run_migrations(&conn)?;
    Ok(conn)
}
